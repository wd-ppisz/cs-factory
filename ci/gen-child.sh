#!/bin/sh
# Generates a child pipeline: one build+validation job per distros/*.yaml manifest.
# Adding a distribution (e.g. from the GUI) = committing ONE manifest file — no
# manual edits of the CI config. custom-* manifests (one-off, local to the build
# host) do not live in the repo, so they never show up here.
set -eu

# NOTE: the heredoc below is UNQUOTED (we need ${d}), so the shell EXPANDS its
# content. NO backticks in its comments — a backticked word gets EXECUTED (a comment
# mentioning the build directory in backticks once produced nine
# "build/: not found" errors and an empty child.yml).

echo "# generated by ci/gen-child.sh — do not edit by hand"
# ONLY_DISTRO narrows the run to one distribution (a comma-separated list works
# too). Without it every iteration on ONE broken distribution rebuilt all of them —
# runner time spent on images that already pass, plus CPU contention that by itself
# broke smoke tests.
# Usage: run the pipeline with the variable ONLY_DISTRO=rocky-10.
ONLY="${ONLY_DISTRO:-}"
if [ -n "$ONLY" ]; then
  echo "run narrowed to: $ONLY" >&2
fi

# Template release number: ONE source of truth in the VERSION file (the Makefile
# reads it too). A hard-coded value made every rebuild OVERWRITE the artifacts of
# already registered templates (same file name, different content). Changing
# template content = bumping VERSION in the same commit. A pipeline VERSION variable
# still takes precedence (one-off build).
RELEASE="$(tr -d '[:space:]' < VERSION)"
echo "$RELEASE" | grep -Eq '^[0-9]+\.[0-9]+$' || { echo "VERSION has a bad format: '$RELEASE' (expected X.Y)" >&2; exit 1; }

found=0
for m in distros/*.yaml; do
  [ -f "$m" ] || continue
  d="$(basename "$m" .yaml)"
  if [ -n "$ONLY" ]; then
    # match a WHOLE list element, not a substring: "rocky-1" must not match
    # "rocky-10", and "rocky-10" must not match "rocky-10-test".
    echo ",$ONLY," | grep -q ",$d," || continue
  fi
  found=1
  cat <<EOF
build_validate_${d}:
  tags: [factory]
  # Generous limit: under TCG virt-customize alone can take 40+ minutes for the RHEL
  # family, and the default hour killed jobs halfway.
  timeout: 3h
  variables:
    # Source image cache OUTSIDE the workspace: git clean -ffdx between jobs wiped
    # the build directory, so every run pulled ~6 GB again.
    CSF_IMAGE_CACHE: /srv/cs-factory/cache
  script:
    - make lint
    # release = build + validation gate + artifact publication to /artifacts/
    # (publication ONLY after PASS — the target order in the Makefile guarantees it)
    - make release DISTRO=${d} VERSION=\${VERSION:-${RELEASE}}
EOF
done

if [ "$found" = 0 ]; then
  if [ -n "$ONLY" ]; then
    # Hard error, not an empty pipeline: a typo in ONLY_DISTRO would otherwise give
    # a GREEN run that built nothing — and a green status without work reads as
    # success.
    echo "ONLY_DISTRO='$ONLY' does not match any manifest in distros/" >&2
    avail=""
    for f in distros/*.yaml; do [ -f "$f" ] && avail="$avail $(basename "$f" .yaml)"; done
    echo "available:$avail" >&2
  else
    echo "no manifests in distros/ — nothing to build" >&2
  fi
  exit 1
fi
